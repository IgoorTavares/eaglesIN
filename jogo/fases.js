/* ==========================================================
   fases.js — roteiro das fases. Cada turno tem um TIPO:
   - dialogo: o personagem fala; o aluno escolhe (ou fala) a resposta.
       { en, pt, ok, aceita[], errados: [[frase, porquê]], resposta }
   - monte: o aluno monta a resposta com as peças (palavras).
       { en, pt, ok, extras[], dica, resposta }
   - repita: o Pavio "sopra" a resposta e o aluno tem que FALAR.
       { en, pt, ok, sopro, dica, resposta }  (sem microfone vira "monte")
   - ouca: teste de ouvido. A frase fica borrada; o aluno escolhe
       o que entendeu, em português.
       { en, pt, pergunta, ok, errados: [[opção, porquê]], resposta }
   Fase de chefão: { chefe: true, vidas: 3 } (pavio mais curto).
   ========================================================== */

